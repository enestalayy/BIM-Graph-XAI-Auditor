"""
XAI Layer — RAG Chain and Grounding Validator.

Implements the LangChain LCEL (LangChain Expression Language) pipeline:

    ClashContext → PromptTemplate → Gemini Flash → JSON Parser → Report

The GroundingValidator post-processes each LLM output to quantify how
many of the model's stated evidence items actually appear in the context.
This produces an objective hallucination score per report.

Anti-Hallucination Architecture:
    1. The retriever provides ONLY graph-sourced facts (no web search, no RAG docs).
    2. The prompt instructs the model to cite each fact in `grounding_evidence`.
    3. The validator checks each `grounding_evidence` item against the context.
    4. Reports with a grounding score < hallucination_threshold are flagged.
    5. All flagged reports are logged for manual review.

The LLM cannot fabricate a GlobalId, rule_id, or intersection_volume because
these are pre-loaded into the context and the prompt tells the model to copy
them verbatim — any deviation is detectable.
"""

from __future__ import annotations

import json
import re
from typing import Any

from langchain_core.output_parsers import JsonOutputParser
from langchain_core.runnables import RunnablePassthrough
from langchain_google_genai import ChatGoogleGenerativeAI

from src.config import settings
from src.logger import get_logger
from src.xai.graph_retriever import ClashContext
from src.xai.prompts import AUDIT_REPORT_PROMPT

logger = get_logger(__name__)

# Fields that MUST appear in every valid audit report.
REQUIRED_REPORT_FIELDS = frozenset(
    {
        "clash_id",
        "rule_id",
        "severity",
        "element_a",
        "element_b",
        "regulation_clause",
        "violation_summary",
        "technical_justification",
        "recommended_action",
        "confidence",
        "grounding_evidence",
        "hallucination_risk",
    }
)


class AuditReport:
    """A validated, structured audit report generated by the LLM.

    Wraps the raw JSON output from the model and adds:
    - A computed grounding score
    - A hallucination_risk flag (from model + validator)
    - The original clash context (for traceability)

    Attributes:
        raw: The raw JSON dict from the LLM.
        context: The ClashContext that was used to generate this report.
        grounding_score: Float 0–1, fraction of evidence items verifiable
            in the context. 1.0 = fully grounded, 0.0 = fully hallucinated.
        is_valid: Whether all required fields are present.
    """

    def __init__(self, raw: dict[str, Any], context: ClashContext) -> None:
        self.raw = raw
        self.context = context
        self.grounding_score: float = 1.0
        self.is_valid: bool = self._validate_fields()

    def _validate_fields(self) -> bool:
        """Check that all required fields are present in the report.

        Returns:
            ``True`` if valid, ``False`` if fields are missing.
        """
        missing = REQUIRED_REPORT_FIELDS - set(self.raw.keys())
        if missing:
            logger.warning(
                "Report missing required fields",
                extra={"clash_id": self.raw.get("clash_id"), "missing": list(missing)},
            )
            return False
        return True

    @property
    def clash_id(self) -> str:
        """The clash ID of this report."""
        return str(self.raw.get("clash_id", ""))

    @property
    def severity(self) -> str:
        """The severity level of this report."""
        return str(self.raw.get("severity", ""))

    @property
    def hallucination_risk(self) -> bool:
        """Whether this report has been flagged for hallucination risk."""
        return bool(self.raw.get("hallucination_risk", False)) or (
            self.grounding_score < settings.hallucination_threshold
        )

    def to_dict(self) -> dict[str, Any]:
        """Serialize the full report including grounding metadata.

        Returns:
            A flat dict with all report fields plus ``grounding_score``
            and a ``context_snapshot`` for audit trail purposes.
        """
        return {
            **self.raw,
            "grounding_score": self.grounding_score,
            "is_valid": self.is_valid,
            "hallucination_risk": self.hallucination_risk,
            "context_snapshot": {
                "clash_id": self.context.clash_id,
                "rule_id": self.context.rule_id,
                "element_a_guid": self.context.element_a.guid,
                "element_b_guid": self.context.element_b.guid,
                "grounding_facts": self.context.grounding_facts,
            },
        }


class GroundingValidator:
    """Validates that LLM-stated evidence appears in the retrieved context.

    For each item in the report's `grounding_evidence` list, this validator
    checks whether the claimed fact appears (case-insensitive substring match)
    in the full context string.

    A grounding score of 1.0 means every cited piece of evidence was found
    in the context; 0.0 means none of it was verifiable.
    """

    def validate(self, report: AuditReport, context_string: str) -> AuditReport:
        """Compute grounding score and update the report in-place.

        Args:
            report: The audit report to validate.
            context_string: The full context string passed to the LLM.

        Returns:
            The same report object with ``grounding_score`` updated.
        """
        evidence_items: list[str] = report.raw.get("grounding_evidence", [])

        if not evidence_items:
            # Model cited no evidence — suspicious but not outright hallucination
            report.grounding_score = 0.5
            logger.warning(
                "Report has no grounding evidence",
                extra={"clash_id": report.clash_id},
            )
            return report

        ctx_lower = context_string.lower()
        verified_count = 0

        for item in evidence_items:
            # Normalize: strip whitespace, lowercase
            item_normalized = item.strip().lower()
            # Extract the value part (after the colon if present)
            parts = item_normalized.split(":", 1)
            check_str = parts[1].strip() if len(parts) > 1 else item_normalized

            if check_str and check_str in ctx_lower:
                verified_count += 1
            else:
                logger.debug(
                    "Evidence item not found in context",
                    extra={"clash_id": report.clash_id, "evidence": item},
                )

        score = verified_count / len(evidence_items)
        report.grounding_score = round(score, 3)

        if score < settings.hallucination_threshold:
            logger.warning(
                "Hallucination risk detected",
                extra={
                    "clash_id": report.clash_id,
                    "grounding_score": score,
                    "threshold": settings.hallucination_threshold,
                    "verified": verified_count,
                    "total_evidence": len(evidence_items),
                },
            )

        return report


class AuditRAGChain:
    """LangChain LCEL chain for generating grounded audit reports.

    Composes:
        context → prompt → Gemini Flash → JSON parser → grounding validation

    Example:
        >>> chain = AuditRAGChain()
        >>> report = chain.generate(clash_context)
        >>> print(report.grounding_score)
    """

    def __init__(self) -> None:
        """Initialize the chain with Gemini Flash and the grounding validator."""
        self._llm = ChatGoogleGenerativeAI(
            model=settings.gemini_model,
            temperature=settings.rag_temperature,
            google_api_key=settings.google_api_key,
        )
        self._parser = JsonOutputParser()
        self._validator = GroundingValidator()

        # Build the LCEL chain:
        # context_block → format messages → LLM → strip json → parse
        self._chain = (
            {"context_block": RunnablePassthrough()}
            | AUDIT_REPORT_PROMPT
            | self._llm
            | self._strip_json_markdown
            | self._parser
        )

    def generate(self, context: ClashContext) -> AuditReport:
        """Generate a grounded audit report for a single clash.

        Args:
            context: The clash context retrieved from Neo4j.

        Returns:
            An :class:`AuditReport` with grounding score computed.

        Raises:
            RuntimeError: If the LLM call fails or JSON parsing fails.
        """
        context_string = context.to_llm_context_string()

        logger.info(
            "Generating XAI report",
            extra={"clash_id": context.clash_id, "severity": context.severity},
        )

        try:
            raw_output: dict[str, Any] = self._chain.invoke(context_string)
        except Exception as exc:
            raise RuntimeError(
                f"LLM call failed for clash {context.clash_id}: {exc}"
            ) from exc

        report = AuditReport(raw=raw_output, context=context)
        report = self._validator.validate(report, context_string)

        logger.info(
            "XAI report generated",
            extra={
                "clash_id": context.clash_id,
                "grounding_score": report.grounding_score,
                "hallucination_risk": report.hallucination_risk,
                "is_valid": report.is_valid,
            },
        )
        return report

    def generate_batch(self, contexts: list[ClashContext]) -> list[AuditReport]:
        """Generate reports for a list of clash contexts.

        Processes sequentially to avoid rate-limiting on the Gemini API.
        Failed individual reports are logged and skipped rather than
        aborting the entire batch.

        Args:
            contexts: List of clash contexts.

        Returns:
            List of :class:`AuditReport` instances (excluding failures).
        """
        reports = []
        for i, ctx in enumerate(contexts):
            try:
                report = self.generate(ctx)
                reports.append(report)
                logger.info(
                    "Batch progress",
                    extra={"current": i + 1, "total": len(contexts)},
                )
            except Exception as exc:  # noqa: BLE001
                logger.error(
                    "Report generation failed, skipping",
                    extra={"clash_id": ctx.clash_id, "error": str(exc)},
                )
        return reports

    @staticmethod
    def _strip_json_markdown(content: Any) -> str:
        """Strip markdown code fences from LLM output if present.

        Some LLM responses wrap JSON in ```json ... ``` blocks despite
        being instructed not to. This method handles both cases.

        Args:
            content: The raw LLM message object or string.

        Returns:
            A clean JSON string ready for parsing.
        """
        text = content.content if hasattr(content, "content") else str(content)
        # Strip ```json ... ``` or ``` ... ``` wrappers
        text = re.sub(r"^```(?:json)?\n?", "", text.strip(), flags=re.MULTILINE)
        text = re.sub(r"\n?```$", "", text.strip(), flags=re.MULTILINE)
        return text.strip()
